-- Lab 03：建立練習用的 tablespace / schema / table / index / view
-- 執行方式：db2 -tvf /labs/03-objects/create_objects.sql

CONNECT TO LABDB;

-- 自動儲存 (automatic storage) 的 tablespace，DB2 自行管理容器檔案
CREATE BUFFERPOOL BP8K SIZE 2000 PAGESIZE 8K;
CREATE TABLESPACE TS_DATA PAGESIZE 8K MANAGED BY AUTOMATIC STORAGE BUFFERPOOL BP8K;
CREATE TABLESPACE TS_IDX  PAGESIZE 8K MANAGED BY AUTOMATIC STORAGE BUFFERPOOL BP8K;

CREATE SCHEMA SHOP;

CREATE TABLE SHOP.CUSTOMER (
    CUST_ID    INTEGER      NOT NULL GENERATED ALWAYS AS IDENTITY,
    NAME       VARCHAR(50)  NOT NULL,
    CITY       VARCHAR(30),
    CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (CUST_ID)
) IN TS_DATA INDEX IN TS_IDX;

CREATE TABLE SHOP.ORDERS (
    ORDER_ID   INTEGER       NOT NULL GENERATED ALWAYS AS IDENTITY,
    CUST_ID    INTEGER       NOT NULL,
    AMOUNT     DECIMAL(10,2) NOT NULL,
    ORDER_DATE DATE          NOT NULL DEFAULT CURRENT DATE,
    PRIMARY KEY (ORDER_ID),
    FOREIGN KEY (CUST_ID) REFERENCES SHOP.CUSTOMER (CUST_ID)
) IN TS_DATA INDEX IN TS_IDX;

CREATE INDEX SHOP.IX_ORDERS_CUST ON SHOP.ORDERS (CUST_ID);

CREATE VIEW SHOP.V_CUST_TOTAL AS
    SELECT C.CUST_ID, C.NAME, COUNT(O.ORDER_ID) AS ORDER_CNT, COALESCE(SUM(O.AMOUNT), 0) AS TOTAL
    FROM SHOP.CUSTOMER C LEFT JOIN SHOP.ORDERS O ON C.CUST_ID = O.CUST_ID
    GROUP BY C.CUST_ID, C.NAME;

